def vector_canonical_artifacts() -> list[str]:
    base = [
        path
        for path in canonical_artifacts()
        if path != "paper/cvpr_claim_sections_v1.md"
    ]
    return sorted(dict.fromkeys([*base, *VECTOR_ARTIFACTS]))


